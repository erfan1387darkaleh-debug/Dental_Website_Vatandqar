/* ────────────────────────────────────────────────────────────────
 *  نمایش ساعات کاری (تبدیل ارقام به فارسی)
 * ────────────────────────────────────────────────────────────────
 */

const FA_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];

/** تبدیل ارقام لاتین به فارسی */
export function toPersianDigits(value: string): string {
  return value.replace(/\d/g, (digit) => FA_DIGITS[Number(digit)]);
}

/** نمایش یک بازه ساعتی به فارسی، مثل «۹:۰۰ تا ۱۳:۰۰» */
export function formatHourPeriod({ opens, closes }: HourPeriod): string {
  const [startHour, startMinute] = opens.split(":");
  const [endHour, endMinute] = closes.split(":");
  return `${toPersianDigits(String(Number(startHour)))}:${toPersianDigits(startMinute)} تا ${toPersianDigits(String(Number(endHour)))}:${toPersianDigits(endMinute)}`;
}

